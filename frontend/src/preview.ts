export function sampleOutput(id: string) {
  if (id === 'coding-agent')
    return {
      code: 'def main():\n    print("Nexus preview — no code executed")\n\nif __name__ == "__main__":\n    main()',
    };
  if (id === 'data-agent')
    return {
      data: 'Preview: data specialist output appears here after execution. No dataset was processed.',
    };
  if (id === 'ops-agent')
    return {
      ops: '# Preview only. No deployment performed.\necho "Deployment instructions appear here"',
    };
  return { summary: 'Preview: research findings appear here. No external research was performed.' };
}
export const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));
export async function runPreview(task: string) {
  const epoch = state.epoch,
    p = plan(task);
  beginWorkflow(task, p, true);
  state.sample = false;
  const run: TaskRun = {
    task,
    status: 'Running preview',
    preview: true,
    time: new Date().toLocaleTimeString(),
    plan: p,
  };
  state.runs.push(run);
  setBusy(true);
  feedback('Preview simulation. No code execution or external requests.');
  $('execution-status').textContent = 'Preview running';
  $('execution-caption').textContent = 'Simulated routing and execution';
  displayPipeline(0, task);
  renderHistory();
  addEvent('activity', `Preview planner selected ${p.length} specialist subtasks.`);
  await delay(450);
  if (epoch !== state.epoch) return;
  displayPipeline(1);
  for (const [id, label] of p) {
    state.activeAgent = id;
    workflowUpdate(id, {
      route: 'completed',
      system: 'completed',
      prompt: 'completed',
      model: 'routed',
    });
    renderAgents();
    addEvent('activity', `Preview routed: ${label} → ${id}`);
    await delay(650);
    if (epoch !== state.epoch) return;
    const existing = state.board.find((e) => e.key === id + ':output'),
      entry = {
        key: id + ':output',
        author: id,
        value: sampleOutput(id),
        version: (existing?.version || 0) + 1,
        timestamp: new Date().toISOString(),
      };
    state.board = state.board.filter((e) => e.key !== entry.key);
    state.board.push(entry);
    workflowUpdate(id, { model: 'completed', publish: 'completed' });
    addEvent('output', `${id} published a simulated output (v${entry.version}).`);
    renderBoard();
  }
  displayPipeline(2);
  if (p.some((x) => ['coding-agent', 'ops-agent'].includes(x[0]))) {
    const e = {
      message: 'Preview sandbox: illustrated repair cycle',
      status: 'Simulated · no code executed',
      code: 'print(result)',
      stderr: "NameError: name 'result' is not defined",
      healed_code: 'result = "preview"\nprint(result)',
    };
    state.sandbox.push(e);
    for (const [id] of p) {
      if (workflowSpec(id).code)
        workflowUpdate(id, { sandbox: 'completed', heal: 'healed', sandboxEvent: e });
    }
    addEvent('sandbox', 'Simulated stderr capture → code repair → sandbox retry.');
    renderSandbox();
  }
  await delay(600);
  if (epoch !== state.epoch) return;
  displayPipeline(3);
  state.receipts.unshift({
    task_id: 'preview-' + Date.now(),
    preview: true,
    timestamp: new Date().toISOString(),
    payload_digest: 'Preview only. No real digest or signature generated.',
  });
  addEvent('receipt', 'Preview finished. Unsigned sample receipt added.');
  displayPipeline(4);
  for (const [id] of p) workflowUpdate(id, { receipt: 'completed' });
  run.status = 'Preview complete';
  $('execution-status').textContent = 'Preview complete';
  $('execution-caption').textContent = 'Simulation complete · no real execution';
  state.activeAgent = null;
  setBusy(false);
  feedback('Preview complete. Inspect outputs, sandbox events, and sample receipt.');
  renderHistory();
  renderReceipts();
}
